def load_journal():
    if not JOURNAL.exists():
        return []
    entries = []
    for line in JOURNAL.read_text(encoding="utf-8").splitlines():
        try:
            entries.append(json.loads(line))
        except json.JSONDecodeError:
            continue
    return entries


def pick_topic(journal):
    used = {e.get("topic") for e in journal[-len(TOPICS):]}
    fresh = [t for t in TOPICS if t["id"] not in used]
    return random.choice(fresh or TOPICS)


def generate(topic):
    result = write(
        what=f"Публичный пост в Telegram-канал репетитора на тему: {topic['title']}",
        channel="telegram",
        domain="tutoring",
        message_type="channel_post",
        language="ru",
        profile="informatics",
        facts={
            "аудитория": topic["aud"],
            "проверенные_факты": topic["facts"],
        },
        business_rules=STYLE_RULES,
        voice=VOICE,
    )
    return str(result).strip()


def generate_complete(topic, attempts=3):
    """GLM с thinking иногда обрывает текст посреди строки — берём только
    похожий на законченный пост: достаточно длинный и с концовкой-пунктуацией."""
    last = ""
    for attempt in range(1, attempts + 1):
        last = generate(topic)
        if len(last) >= 400 and last[-1] in ".!?:…)»\"":
            return last
        print(f"  попытка {attempt}: обрывок ({len(last)} зн.), перегенерирую…", flush=True)
    raise SystemExit(f"генерация {attempts} раз подряд дала обрывок, пост не отправляю: {last[-80:]!r}")


async def send(text):
    client = await connect_any("main")
    try:
        msg = await client.send_message(CHANNEL_ID, text, parse_mode="md")
        return msg.id
    finally:
        await client.disconnect()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dry", action="store_true", help="сгенерировать и напечатать, не отправлять")
    parser.add_argument("--topic", help="принудительная тема по id (для проверки)")
    args = parser.parse_args()

    if args.topic:
        topic = next((t for t in TOPICS if t["id"] == args.topic), None)
        if topic is None:
            sys.exit(f"нет темы {args.topic!r}; доступно: {', '.join(t['id'] for t in TOPICS)}")
    else:
        topic = pick_topic(load_journal())

    print(f"тема: {topic['id']} ({topic['aud']}), генерирую…", flush=True)
    text = generate_complete(topic)
    print(text, flush=True)

    if args.dry:
        return

    msg_id = asyncio.run(send(text))
    JOURNAL.parent.mkdir(parents=True, exist_ok=True)
    with JOURNAL.open("a", encoding="utf-8") as fh:
        fh.write(
            json.dumps(
                {
                    "ts": datetime.now(timezone.utc).isoformat(timespec="seconds"),
                    "topic": topic["id"],
                    "aud": topic["aud"],
                    "chars": len(text),
                    "msg_id": msg_id,
                },
                ensure_ascii=False,
            )
            + "\n"
        )
    print(f"отправлено: msg_id={msg_id}, {len(text)} зн.", flush=True)


if __name__ == "__main__":
    main()
